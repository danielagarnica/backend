-- =====================================================================
-- PocketPet - Esquema de base de datos (PostgreSQL / Supabase)
-- Basado en diagramas/Modelo de datos.jpeg del repositorio POCKETPET.
--
-- Se puede ejecutar varias veces sin romper nada (es idempotente):
--   - Desde el SQL Editor de Supabase (pegar y ejecutar), o
--   - Con "npm run db:setup" (usa DATABASE_URL del archivo .env).
--
-- Nombres: el diagrama usa id_usuario, id_meta, monto_actual...
-- Aquí se usan los nombres que ya espera el backend:
--   id_<tabla>   -> id
--   id_usuario   -> usuario_id
--   id_meta      -> meta_id
--   monto_actual -> monto_ahorrado
-- =====================================================================

BEGIN;

-- ---------------------------------------------------------------------
-- USUARIOS (RF-01, RF-02)
-- La contraseña se guarda solo como hash bcrypt (RNF-03).
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.usuarios (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre          VARCHAR(100) NOT NULL CHECK (length(trim(nombre)) > 0),
  email           VARCHAR(255) NOT NULL UNIQUE CHECK (email = lower(email)),
  password_hash   TEXT         NOT NULL,
  fecha_creacion  TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);

-- ---------------------------------------------------------------------
-- CATEGORIAS de gasto (catálogo fijo)
-- "codigo" es el valor que envía el <select> de gastos.html.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.categorias (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo       VARCHAR(30)  NOT NULL UNIQUE,
  nombre       VARCHAR(60)  NOT NULL,
  descripcion  VARCHAR(255)
);

INSERT INTO public.categorias (codigo, nombre, descripcion) VALUES
  ('alimentacion',    'Alimentación',        'Comida, mercado y restaurantes'),
  ('transporte',      'Transporte',          'Buses, gasolina, taxis y similares'),
  ('entretenimiento', 'Entretenimiento',     'Salidas, suscripciones y ocio'),
  ('servicios',       'Servicios y Recibos', 'Agua, luz, internet, celular'),
  ('educacion',       'Educación',           'Matrículas, cursos y materiales'),
  ('otros',           'Otros',               'Gastos que no encajan en otra categoría')
ON CONFLICT (codigo) DO NOTHING;

-- ---------------------------------------------------------------------
-- INGRESOS (RF-04)  USUARIO 1 --- N INGRESO
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.ingresos (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id      BIGINT        NOT NULL REFERENCES public.usuarios (id) ON DELETE CASCADE,
  tipo            VARCHAR(100)  NOT NULL CHECK (length(trim(tipo)) > 0),  -- "descripcion" en el diagrama
  monto           NUMERIC(14,2) NOT NULL CHECK (monto > 0),
  fecha           DATE          NOT NULL,
  notas           TEXT          NOT NULL DEFAULT '',
  fecha_creacion  TIMESTAMPTZ   NOT NULL DEFAULT NOW()
);

-- ---------------------------------------------------------------------
-- GASTOS (RF-05)  USUARIO 1 --- N GASTO,  CATEGORIA 1 --- N GASTO
-- "categoria" guarda el código y es FK a categorias.codigo, así la API
-- sigue recibiendo y devolviendo "alimentacion", "transporte", etc.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.gastos (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id      BIGINT        NOT NULL REFERENCES public.usuarios (id) ON DELETE CASCADE,
  categoria       VARCHAR(30)   NOT NULL REFERENCES public.categorias (codigo) ON UPDATE CASCADE,
  descripcion     VARCHAR(150)  NOT NULL CHECK (length(trim(descripcion)) > 0),
  monto           NUMERIC(14,2) NOT NULL CHECK (monto > 0),
  fecha           DATE          NOT NULL,
  notas           TEXT          NOT NULL DEFAULT '',
  fecha_creacion  TIMESTAMPTZ   NOT NULL DEFAULT NOW()
);

-- ---------------------------------------------------------------------
-- METAS de ahorro (RF-06, RF-07)  USUARIO 1 --- N META_AHORRO
-- "progreso" (0-100) se calcula solo a partir de los montos.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.metas (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id      BIGINT        NOT NULL REFERENCES public.usuarios (id) ON DELETE CASCADE,
  nombre          VARCHAR(100)  NOT NULL CHECK (length(trim(nombre)) > 0),
  categoria       VARCHAR(30)   NOT NULL,
  monto_objetivo  NUMERIC(14,2) NOT NULL CHECK (monto_objetivo > 0),
  monto_ahorrado  NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (monto_ahorrado >= 0),
  fecha_limite    DATE          NOT NULL,
  progreso        NUMERIC(5,2)  GENERATED ALWAYS AS (
                    LEAST(100, ROUND(monto_ahorrado * 100 / monto_objetivo, 2))
                  ) STORED,
  fecha_creacion  TIMESTAMPTZ   NOT NULL DEFAULT NOW()
);

-- ---------------------------------------------------------------------
-- AHORROS (RF-08)  USUARIO 1 --- N AHORRO,  META_AHORRO 1 --- N AHORRO
-- "nombre" es el destino del ahorro. Si coincide con el nombre de una
-- meta del usuario, el backend llena meta_id y suma el monto a la meta.
-- Si se borra la meta, el ahorro se conserva (meta_id queda en NULL):
-- borrar una meta no debe hacer desaparecer dinero ya ahorrado.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.ahorros (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id      BIGINT        NOT NULL REFERENCES public.usuarios (id) ON DELETE CASCADE,
  meta_id         BIGINT        REFERENCES public.metas (id) ON DELETE SET NULL,
  nombre          VARCHAR(100)  NOT NULL CHECK (length(trim(nombre)) > 0),  -- "destino" en el diagrama
  monto           NUMERIC(14,2) NOT NULL CHECK (monto > 0),
  fecha           DATE          NOT NULL,
  notas           TEXT          NOT NULL DEFAULT '',
  fecha_creacion  TIMESTAMPTZ   NOT NULL DEFAULT NOW()
);

-- ---------------------------------------------------------------------
-- ÍNDICES (los del diagrama). Postgres no indexa las FK por sí solo.
-- ---------------------------------------------------------------------
CREATE INDEX IF NOT EXISTS idx_ingreso_usuario   ON public.ingresos (usuario_id);
CREATE INDEX IF NOT EXISTS idx_gasto_usuario     ON public.gastos   (usuario_id);
CREATE INDEX IF NOT EXISTS idx_gasto_categoria   ON public.gastos   (categoria);
CREATE INDEX IF NOT EXISTS idx_meta_usuario      ON public.metas    (usuario_id);
CREATE INDEX IF NOT EXISTS idx_ahorro_usuario    ON public.ahorros  (usuario_id);
CREATE INDEX IF NOT EXISTS idx_ahorro_meta       ON public.ahorros  (meta_id);
-- Para buscar la meta por nombre al registrar un ahorro
CREATE INDEX IF NOT EXISTS idx_meta_usuario_nombre
  ON public.metas (usuario_id, lower(trim(nombre)));

-- ---------------------------------------------------------------------
-- SEGURIDAD
-- Supabase expone las tablas de "public" por su API REST con la clave
-- anon. Como aquí todo pasa por nuestro backend (que entra con el rol
-- postgres y no está sujeto a RLS), se activa RLS sin políticas y se
-- quitan permisos a anon/authenticated: nadie puede leer las tablas
-- directamente desde el navegador con la clave pública.
-- ---------------------------------------------------------------------
ALTER TABLE public.usuarios   ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.categorias ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.ingresos   ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.gastos     ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.metas      ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.ahorros    ENABLE ROW LEVEL SECURITY;

DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
    REVOKE ALL ON public.usuarios, public.categorias, public.ingresos,
                  public.gastos, public.metas, public.ahorros FROM anon;
  END IF;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
    REVOKE ALL ON public.usuarios, public.categorias, public.ingresos,
                  public.gastos, public.metas, public.ahorros FROM authenticated;
  END IF;
END
$$;

COMMIT;
