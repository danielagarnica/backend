-- =====================================================================
-- Migración 001: completa la base que ya existía en Supabase para que
-- coincida con database/schema.sql. NO borra datos.
--
-- Qué hace:
--   1. Crea la tabla categorias y su catálogo.
--   2. gastos.categoria pasa a ser FK de categorias.codigo.
--   3. Agrega metas.progreso (calculado automáticamente).
--   4. Agrega ahorros.meta_id y enlaza los ahorros existentes con la meta
--      del mismo nombre (no cambia monto_ahorrado: ya se sumó antes).
--   5. Montos deben ser > 0 y textos obligatorios no vacíos.
--   6. Índices que faltaban.
--   7. Quita los permisos de anon/authenticated (clave pública de Supabase).
--
-- Es idempotente: se puede ejecutar varias veces.
-- Se ejecuta con "npm run db:migrate" (dentro de una transacción: si algo
-- falla, no se aplica nada).
-- =====================================================================

-- 1. CATEGORIAS ---------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.categorias (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo       VARCHAR(30)  NOT NULL UNIQUE,
  nombre       VARCHAR(60)  NOT NULL,
  descripcion  VARCHAR(255)
);

INSERT INTO public.categorias (codigo, nombre, descripcion) VALUES
  ('alimentacion',    'Alimentación',        'Comida, mercado y restaurantes'),
  ('transporte',      'Transporte',          'Buses, gasolina, taxis y similares'),
  ('entretenimiento', 'Entretenimiento',     'Salidas, suscripciones y ocio'),
  ('servicios',       'Servicios y Recibos', 'Agua, luz, internet, celular'),
  ('educacion',       'Educación',           'Matrículas, cursos y materiales'),
  ('otros',           'Otros',               'Gastos que no encajan en otra categoría')
ON CONFLICT (codigo) DO NOTHING;

-- 2. GASTOS.CATEGORIA -> CATEGORIAS.CODIGO ------------------------------
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'gastos_categoria_fkey') THEN
    ALTER TABLE public.gastos
      ADD CONSTRAINT gastos_categoria_fkey
      FOREIGN KEY (categoria) REFERENCES public.categorias (codigo) ON UPDATE CASCADE;
  END IF;
END
$$;

-- 3. METAS.PROGRESO -----------------------------------------------------
ALTER TABLE public.metas
  ADD COLUMN IF NOT EXISTS progreso NUMERIC(5,2) GENERATED ALWAYS AS (
    LEAST(100, ROUND(monto_ahorrado * 100 / monto_objetivo, 2))
  ) STORED;

-- 4. AHORROS.META_ID ----------------------------------------------------
ALTER TABLE public.ahorros
  ADD COLUMN IF NOT EXISTS meta_id BIGINT REFERENCES public.metas (id) ON DELETE SET NULL;

UPDATE public.ahorros a
   SET meta_id = (
         SELECT m.id FROM public.metas m
          WHERE m.usuario_id = a.usuario_id
            AND lower(trim(m.nombre)) = lower(trim(a.nombre))
          ORDER BY m.id DESC
          LIMIT 1
       )
 WHERE a.meta_id IS NULL;

-- 5. VALIDACIONES -------------------------------------------------------
-- Montos: de ">= 0" a "> 0" (un ingreso/gasto/ahorro de $0 no tiene sentido)
ALTER TABLE public.ingresos DROP CONSTRAINT IF EXISTS ingresos_monto_check,
  ADD CONSTRAINT ingresos_monto_check CHECK (monto > 0);
ALTER TABLE public.gastos   DROP CONSTRAINT IF EXISTS gastos_monto_check,
  ADD CONSTRAINT gastos_monto_check   CHECK (monto > 0);
ALTER TABLE public.ahorros  DROP CONSTRAINT IF EXISTS ahorros_monto_check,
  ADD CONSTRAINT ahorros_monto_check  CHECK (monto > 0);

-- Textos obligatorios no vacíos y correo en minúsculas
ALTER TABLE public.usuarios DROP CONSTRAINT IF EXISTS usuarios_nombre_check,
  ADD CONSTRAINT usuarios_nombre_check CHECK (length(trim(nombre)) > 0);
ALTER TABLE public.usuarios DROP CONSTRAINT IF EXISTS usuarios_email_check,
  ADD CONSTRAINT usuarios_email_check CHECK (email = lower(email));
ALTER TABLE public.ingresos DROP CONSTRAINT IF EXISTS ingresos_tipo_check,
  ADD CONSTRAINT ingresos_tipo_check CHECK (length(trim(tipo)) > 0);
ALTER TABLE public.gastos   DROP CONSTRAINT IF EXISTS gastos_descripcion_check,
  ADD CONSTRAINT gastos_descripcion_check CHECK (length(trim(descripcion)) > 0);
ALTER TABLE public.metas    DROP CONSTRAINT IF EXISTS metas_nombre_check,
  ADD CONSTRAINT metas_nombre_check CHECK (length(trim(nombre)) > 0);
ALTER TABLE public.ahorros  DROP CONSTRAINT IF EXISTS ahorros_nombre_check,
  ADD CONSTRAINT ahorros_nombre_check CHECK (length(trim(nombre)) > 0);

-- 6. ÍNDICES QUE FALTABAN -----------------------------------------------
CREATE INDEX IF NOT EXISTS idx_gastos_categoria ON public.gastos (categoria);
CREATE INDEX IF NOT EXISTS idx_ahorros_meta     ON public.ahorros (meta_id);
CREATE INDEX IF NOT EXISTS idx_metas_usuario_nombre
  ON public.metas (usuario_id, lower(trim(nombre)));

-- 7. SEGURIDAD ----------------------------------------------------------
ALTER TABLE public.categorias ENABLE ROW LEVEL SECURITY;

DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
    REVOKE ALL ON public.usuarios, public.categorias, public.ingresos,
                  public.gastos, public.metas, public.ahorros FROM anon;
  END IF;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
    REVOKE ALL ON public.usuarios, public.categorias, public.ingresos,
                  public.gastos, public.metas, public.ahorros FROM authenticated;
  END IF;
END
$$;
